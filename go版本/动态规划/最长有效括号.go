/*
思路概括（两种方法）：
1. DP 方法：dp[i] 表示以 s[i] 结尾的最长有效括号子串长度。
   - s[i]=='(' 则 dp[i]=0。
   - s[i]==')' 时分两种情况：s[i-1]=='(' 则 dp[i]=dp[i-2]+2；s[i-1]==')' 且能匹配到前面的 '(' 则 dp[i]=dp[i-1]+dp[j-1]+2。
2. 栈方法：栈中存储"可能作为新有效段起点的索引"。初始压入 -1，遇 '(' 压入索引，遇 ')' 弹出栈顶：
   - 栈空则当前为无效 ')'，压入当前索引作为新起点。
   - 栈非空则当前有效长度 = i - 栈顶，更新最大值。

复杂度：
- 时间：O(N)，遍历一次。
- 空间：O(N)，dp 数组或栈深度。
*/

package main

import (
	"fmt"
)

func main() {
	s := ")((()()))"
	fmt.Println("动态规划方法结果:", dp_method(s))
	fmt.Println("栈方法结果:", stack_method(s))
}

// ==================== 方法一：动态规划（DP） ====================

// dp_method 使用动态规划求最长有效括号子串的长度
// 核心思想：dp[i] 表示以 s[i] 结尾的最长有效括号子串的长度
func dp_method(s string) int {
	n := len(s)
	if n == 0 {
		return 0
	}

	// dp[i]：以索引 i 处字符结尾的最长有效括号长度
	dp := make([]int, n)
	ans := 0 // 记录全局最大值

	// 从左到右遍历字符串（i 从 1 开始，因为单个 ')' 不可能构成有效括号）
	for i := 1; i < n; i++ {
		if s[i] == ')' {
			// 情况 1：s[i-1] == '('，即形如 "...()"
			if s[i-1] == '(' {
				// 基础匹配：s[i-1] 和 s[i] 构成一对 "()"
				dp[i] = 2
				// 如果前面还有字符（i >= 2），加上前面已经计算好的有效长度
				if i >= 2 {
					dp[i] += dp[i-2]
				}
			} else if dp[i-1] > 0 {
				// 情况 2：s[i-1] == ')' 且 dp[i-1] > 0，说明前面有一段有效括号
				// 例如：...((...))，当前是最后一个 ')'
				// 我们需要找到这段有效括号前面的那个字符，看是不是 '('

				// j 是当前有效段前面一个位置的索引
				// 举例：s = "(()())"，i=5（最后一个')'），dp[4]=4（"()()" 长度为4）
				// 那么 j = 5 - 4 - 1 = 0，检查 s[0] 是否为 '('
				j := i - dp[i-1] - 1

				// 如果 j 合法，且 s[j] 是 '('，说明可以扩展
				if j >= 0 && s[j] == '(' {
					// 当前有效长度 = 内部有效长度（dp[i-1]） + 外层一对括号（2）
					dp[i] = dp[i-1] + 2
					// 如果 j 前面还有内容（j > 0），还要加上 j-1 位置的有效长度
					// 例如：()(())，在处理最后一个 ')' 时，要把前面的 "()" 也连起来
					if j > 0 {
						dp[i] += dp[j-1]
					}
				}
				// 如果 s[j] 不是 '('，则 dp[i] 保持为 0（默认值）
			}
			// 更新全局最大值
			ans = max(ans, dp[i])
		}
		// 如果 s[i] == '('，dp[i] 保持为 0（因为有效括号不能以 '(' 结尾）
	}
	return ans
}

// ==================== 方法二：栈（Stack） ====================

// stack_method 使用栈来求最长有效括号子串的长度
// 核心思想：栈中存储的是“可能作为新有效段起点的索引”
// 初始时压入 -1 作为基准（边界哨兵）
func stack_method(s string) int {
	ans := 0
	// 初始化栈，压入 -1 作为起始基准（表示上一个无效位置）
	stk := []int{-1}

	for i := 0; i < len(s); i++ {
		if s[i] == '(' {
			// 遇到 '('，直接入栈（它可能是未来匹配的起点）
			stk = append(stk, i)
		} else {
			// 遇到 ')'，尝试匹配
			// 先弹出栈顶（可能是 '(' 的位置，也可能是无效位置）
			stk = stk[:len(stk)-1]

			if len(stk) == 0 {
				// 栈空了，说明这次 ')' 没有匹配的 '('
				// 将当前 i 作为新的“无效位置”入栈，作为后续计算的起点
				stk = append(stk, i)
			} else {
				// 栈不为空，说明栈顶是上一个未被匹配的 '(' 或无效位置
				// 当前有效长度 = i - stk[len(stk)-1]
				// 例如：s = "()(())"，当 i=5 时，栈顶是 1（第一个 '(' 后的位置）
				// i - 1 = 4，但实际有效长度是 6？不对 —— 实际例子中会正确计算
				// 关键：stk 顶部始终是“上一个无效位置”，所以 i - top 就是当前有效长度
				ans = max(ans, i-stk[len(stk)-1])
			}
		}
	}
	return ans
}

// 辅助函数：返回两个整数的最大值
func max(a, b int) int {
	if a > b {
		return a
	}
	return b
}
